"""Build js/data-ch11.js from the same data files the Chapter 11 deck draws its charts from.

Run from the repo root:  python3 tools/build_data.py
Source CSVs live in ../_deck-builder/data (OWID downloads of NOAA/EPA ice-core CO2, Global Carbon Budget,
HadCRUT5, Hawaii Ocean Time-series; Judd et al. 2024 PhanDA; Maricopa County DPH heat-death reports)."""
import csv, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.normpath(os.path.join(HERE, '..', '..', '_deck-builder', 'data'))
OUT = os.path.join(HERE, '..', 'js', 'data-ch11.js')


def rows(name):
    return list(csv.DictReader(open(os.path.join(SRC, name))))


def decyear(day):
    y, m, d = (int(x) for x in day.split('-'))
    return round(y + (m - 1) / 12 + (d - 1) / 365, 3)


co2 = [[int(r['year']), round(float(r['co2_concentration']), 1)] for r in rows('owid-co2-long-term-concentration.csv')]
emis = [[int(r['year']), round(float(r['emissions_total']) / 1e9, 2)] for r in rows('owid-annual-co2-emissions.csv')]
temp = [[int(r['year']), round(float(r['near_surface_temperature_anomaly']), 3)]
        for r in rows('owid-temperature-anomaly-hadcrut5-1861-1890.csv') if r['entity'] == 'World' and int(r['year']) <= 2025]
ph_rows = rows('owid-seawater-ph-hot-aloha.csv')
ph_pts = [[decyear(r['day']), round(float(r['ocean_ph']), 4)] for r in ph_rows if r['ocean_ph']]
ph_avg = [[decyear(r['day']), round(float(r['ocean_ph_yearly_average']), 4)] for r in ph_rows if r['ocean_ph_yearly_average']]
phx = [[int(r[0]), int(r[1])] for r in csv.reader(open(os.path.join(SRC, 'maricopa-heat-deaths.csv'))) if r and r[0].strip().isdigit()]
phanda = [[float(r['AverageAge']), round(float(r['GMST_16']), 2), round(float(r['GMST_50']), 2), round(float(r['GMST_84']), 2)]
          for r in rows('phanda-gmst-judd2024.csv')]
us_heat = []
for r in csv.reader(open(os.path.join(SRC, 'epa-heat-deaths-fig1.csv'))):
    if r and r[0].strip().isdigit() and len(r) > 1 and r[1].strip():
        us_heat.append([int(r[0]), float(r[1])])
world = next(r for r in rows('willingness-climate-action.csv') if r['Entity'] == 'World')

D = {
    'co2': co2, 'emis': emis, 'temp': temp, 'phPts': ph_pts, 'phAvg': ph_avg, 'phx': phx, 'phanda': phanda, 'usHeat': us_heat,
    'willing': {'actual': float(world['Actual share who said they were willing to give 1% of their income']),
                'predicted': float(world['Predicted share willing to give'])},
}
with open(OUT, 'w') as f:
    f.write('/* Generated by tools/build_data.py from the Chapter 11 deck data. Do not edit by hand. */\n')
    f.write('window.CH11_DATA=' + json.dumps(D, separators=(',', ':')) + ';\n')
print('wrote', OUT, os.path.getsize(OUT), 'bytes;', {k: len(v) for k, v in D.items() if isinstance(v, list)})
